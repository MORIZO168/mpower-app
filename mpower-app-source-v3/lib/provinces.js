export function matchProvinces(q, limit = 6) {
  const s = (q || "").trim();
  if (!s) return [];
  const starts = PROVINCES.filter((p) => p.startsWith(s));
  const contains = PROVINCES.filter((p) => !p.startsWith(s) && p.includes(s));
  return [...starts, ...contains].slice(0, limit);
}
